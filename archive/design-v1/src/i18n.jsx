function readStoredLang() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    return stored === 'en' || stored === 'fr' ? stored : 'fr';
  } catch {
    return 'fr';
  }
}

const pad = (n) => String(n).padStart(2, '0');
const capitalize = (text) => text.charAt(0).toUpperCase() + text.slice(1);

function buildApi(lang) {
  const isFr = lang === 'fr';
  const locale = isFr ? 'fr-FR' : 'en-GB';
  const fmt = (n) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, isFr ? ' ' : '.');

  return {
    lang,
    locale,
    fmt,
    t: (key, vars) => {
      const text = messages[lang][key] ?? messages.en[key] ?? key;
      return vars ? text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '') : text;
    },
    pct: (n) => (isFr ? `${String(n).replace('.', ',')} %` : `${n}%`),
    money: (n) => (isFr ? `${fmt(n)} $` : `$${fmt(n)}`),
    dateTime: (date) => {
      const day = `${pad(date.getDate())}/${pad(date.getMonth() + 1)}/${date.getFullYear()}`;
      const h = date.getHours();
      const min = pad(date.getMinutes());
      if (isFr) return `${day} ${pad(h)}:${min}`;
      return `${day} ${h % 12 === 0 ? 12 : h % 12}:${min} ${h < 12 ? 'AM' : 'PM'}`;
    },
    longDate: (date) => date.toLocaleDateString(locale, { day: '2-digit', month: 'short', year: 'numeric' }),
    dayLabel: (date) => capitalize(date.toLocaleDateString(locale, { weekday: 'long', day: 'numeric', month: 'long' })),
    monthYear: (date) => capitalize(date.toLocaleDateString(locale, { month: 'long', year: 'numeric' })),
  };
}

const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(readStoredLang);

  useEffect(() => {
    document.documentElement.lang = lang;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      // Le stockage peut être bloqué : la langue reste valable pour la session.
    }
  }, [lang]);

  const value = useMemo(() => ({ ...buildApi(lang), setLang }), [lang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
